#!/usr/bin/env python3
"""Writes the README's "Works with the stock BIOS" section from Tools/data/bios.json (KICAD.md K34), and with
--all --out PATH the family's chart of every board in all five repositories.

  gen.py                       write the README
  gen.py --check               exit 1 if a README is out of date, or a revision has no entry (or one entry too many)
  gen.py --all --out PATH      also write the family's chart to PATH, as Markdown

bios.json is hand-written: for each board, the revisions an entry covers, its category, a one-line reason and the
reason's source (the BIOS's probe in Kernal.asm, a bench result, the netlist or a README). Every revision in
Hardware/ needs exactly one entry.

The stock BIOS is the one a board's machine ships with: BIOS 2.x on the ACE, BIOS 1.x (6502-BIOS's v1.x branch) on
the COB, DEV, KIM and VCS. A card counts as the BIOS finds it when its window jumper is on the window the BIOS
expects, as the README's Jumpers table says; a card set to another window is the builder's experiment."""
import os,sys,re,collections,glob
H=os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0,os.path.dirname(H));from common import K,SCOPE,ALL,load
B=[e for e in load('bios.json') if e['repo'] in SCOPE]
BIOS={'ACE':'2.x'};BIOS.update({r:'1.x' for r in ALL if r!='ACE'})
MACHINE={'ACE':'the ACE','COB':'the COB','DEV':'the DEV','KIM':'the KIM','VCS':'the VCS'}
PRO='a PICO9918 PRO running 6502-PICOVDP, set up as the [ACE\'s video card](https://github.com/acwright/6502-ACE#video-card) is'
TWO={'ACE':'',
     'COB':f'A COB can also run BIOS 2.x with a VGA Card 1.1 carrying {PRO}. Today\'s COBs, built with a VGA Card 1.0 or a Video Card, stay on BIOS 1.x. ',
     'VCS':f'A VCS can also run BIOS 2.x with an Output Board 1.1 carrying {PRO}. Today\'s VCSs, built with an Output Board 1.0, stay on BIOS 1.x. ',
     'KIM':'The KIM also runs BIOS 2.x: it has no video card, and the KC Monitor calls only Kernal routines (`InitSC`, `KernalInit`) that sit at the same addresses in both. ',
     'DEV':'The DEV can\'t run BIOS 2.x yet: its DB Emulator firmware is written for BIOS 1.x. '}
CATS={'out of the box':'Out of the box','after a step':'After a step','not used':'Not used by the BIOS',
      'nothing to support':'Nothing to support'}
BEGIN='<!-- Stock BIOS: generated by Tools/bios/gen.py from Tools/data/bios.json. Edit that file, not this section. -->'
END='<!-- End of stock BIOS -->'
AFTER='<!-- End of which revision to make -->'
DEFINE="""- **Out of the box:** the BIOS finds the board and uses it, built from its parts list with the jumpers the [Jumpers](#jumpers) table gives. A card counts only on the window the BIOS expects; on another window it's the builder's experiment.
- **After a step:** it works once the builder does what the entry names, beyond the parts list and the jumpers.
- **Not used by the BIOS:** safe beside it, but your own software drives it.
- **Nothing to support:** the board has no registers for the BIOS to find, such as a backplane, a helper behind a card, or a cartridge's programmer."""
def nat(s): return [int(x) if x.isdigit() else x for x in re.split(r'(\d+)',s)]
def intro(repo):
    v=BIOS[repo]
    where='the `main` branch of [6502-BIOS](https://github.com/acwright/6502-BIOS)' if v=='2.x' else 'the `v1.x` branch of [6502-BIOS](https://github.com/acwright/6502-BIOS)'
    other='The other machines run BIOS 1.x, for a TMS9918A.' if v=='2.x' else 'The ACE runs BIOS 2.x, for a 6502-PICOVDP.'
    return (f"## Works with the stock BIOS\n\nWhether each board works with the stock BIOS, and what it takes if not. "
            f"The stock BIOS for {MACHINE[repo]} is **BIOS {v}**, from {where}. {other} {TWO[repo]}"
            f"The BIOS looks for each card in its own 1 KB window at boot, and uses only what it finds.\n\n{DEFINE}\n\n"
            "| Board | Rev | Stock BIOS | Why | Source |\n|---|---|---|---|---|\n")
def rows(repo):
    out=[]
    for e in sorted([e for e in B if e['repo']==repo],key=lambda e:(e['board'],nat(e['revs'][0]))):
        out.append((e['board'],', '.join(e['revs']),CATS[e['category']],e['reason'],e['source']))
    return out
def section(repo):
    return intro(repo)+''.join(f"| {b} | {r} | **{c}** | {w} | {s} |\n" for b,r,c,w,s in rows(repo))+'\n'
def write(repo,check):
    p=f'{K}6502-{repo}/README.md';t0=open(p,encoding='utf8').read();body=BEGIN+'\n'+section(repo)+END+'\n'
    if BEGIN in t0:
        i=t0.index(BEGIN);j=t0.index(END,i)+len(END)+1;new=t0[:i]+body+t0[j:]
    else:
        j=t0.index(AFTER)+len(AFTER)+1;new=t0[:j]+'\n'+body+t0[j:]
        toc='- [Which revision to make](#which-revision-to-make)\n'
        if toc not in new: raise SystemExit(f'{repo}: no table-of-contents line {toc!r}')
        new=new.replace(toc,toc+'- [Works with the stock BIOS](#works-with-the-stock-bios)\n',1)
    if check: return new==t0
    if new!=t0: open(p,'w',encoding='utf8').write(new)
    return True
def coverage():
    """Every revision in Hardware/ has exactly one entry, and every entry is complete and names a real revision."""
    bad=[];have=collections.Counter()
    for e in B:
        for f in ('board','revs','category','reason','source'):
            if not e.get(f): bad.append(f'{e["repo"]}|{e.get("board")}: entry has no {f}')
        if e.get('category') not in CATS: bad.append(f'{e["repo"]}|{e.get("board")}: category {e.get("category")!r} is not one of {", ".join(CATS)}')
        for r in e.get('revs',[]): have[(e['repo'],e['board'],r)]+=1
    real=set()
    for repo in SCOPE:
        for f in glob.glob(f'{K}6502-{repo}/Hardware/*/Rev */*.kicad_pcb'):
            p=f.split('/');real.add((repo,p[-3],p[-2][4:]))
    for k in sorted(real):
        if have[k]==0: bad.append(f'{"|".join(k)} has no entry in bios.json')
    for k,n in sorted(have.items()):
        if n>1: bad.append(f'{"|".join(k)} has {n} entries in bios.json')
        if k not in real: bad.append(f'{"|".join(k)} is in bios.json but not in Hardware/')
    return bad
def chart(path):
    o=["# Works with the stock BIOS: the family's chart","",
       "Generated by `Tools/bios/gen.py --all --out`, from each repository's `Tools/data/bios.json` (`KICAD.md` K34). "
       "The stock BIOS is BIOS 2.x on the ACE and BIOS 1.x on the COB, DEV, KIM and VCS.","",DEFINE,"",
       "| Repository | Board | Rev | Stock BIOS | Why | Source |","|---|---|---|---|---|---|"]
    n=collections.Counter()
    unlink=lambda s:re.sub(r'\[([^\]]+)\]\(#[^)]*\)',r'\1',s)   # a README's own anchors mean nothing outside it
    for repo in ALL:
        for b,r,c,w,s in rows(repo):
            o.append(f"| {repo} | {b} | {r} | **{c}** | {unlink(w)} | {unlink(s)} |");n[c]+=len(r.split(', '))
    o+=["",'Revisions: '+', '.join(f'{c} {n[c]}' for c in CATS.values())+'.',""]
    open(path,'w',encoding='utf8').write('\n'.join(o))
if __name__=='__main__':
    check='--check' in sys.argv;bad=coverage()
    for repo in SCOPE:
        if not write(repo,check): bad.append(f'{repo} README "Works with the stock BIOS" section is out of date')
    if '--out' in sys.argv:
        if SCOPE!=ALL: raise SystemExit('--out writes the family chart: run it with --all')
        chart(sys.argv[sys.argv.index('--out')+1]);print('wrote',sys.argv[sys.argv.index('--out')+1])
    for b in bad: print(b)
    print('bios:',len(B),'entries,',len(bad),'faults');sys.exit(1 if bad else 0)
