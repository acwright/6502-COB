#!/usr/bin/env python3
"""Writes the "Jumpers" section of the README from Tools/data/jumpers.json. With --all, in all five repositories.

  gen.py            write the README
  gen.py --check    exit 1 if a README is out of date, a jumper on any revision isn't in jumpers.json, or a solder
                    jumper's "as shipped" disagrees with its footprint

jumpers.json is hand-written: what each jumper is for, how it's shipped, and what a builder does with it. The tables
and the BOM's shunt rows (Tools/bom/gen_bom.py) come from it."""
import os,sys,json,re,collections
H=os.path.dirname(os.path.abspath(__file__));sys.path.insert(0,H)
sys.path.insert(0,os.path.dirname(os.path.dirname(os.path.abspath(__file__))));import common;from common import K,SCOPE,files,load,save
J=[e for e in load('jumpers.json') if e['repo'] in SCOPE]
BEGIN='<!-- Jumpers: generated by Tools/jumpers/gen.py from Tools/data/jumpers.json. Edit that file, not this section. -->'
END='<!-- End of jumpers -->'
INTRO="""## Jumpers

Some boards have solder jumpers, and pin headers that take a shunt. The tables below give every one: what it's for, how the board is shipped, and what to do with it. The **Needed** column marks the ones that matter:

- **To run**: the board doesn't work until this is set. Set it before the first power-up.
- **For serial**, **For interrupts**, **For cartridges**: the board runs without it, but that feature doesn't.
- Blank: leave it as shipped unless you want what it offers.

Where a header needs a shunt, the board's BOM lists it.

"""
NONE="None of this repository's boards has a jumper.\n\n"
def nat(s): return [int(x) if x.isdigit() else x for x in re.split(r'(\d+)',s)]
def section(repo):
    E=[e for e in J if e['repo']==repo]
    if not E: return INTRO.split('\n\n')[0]+'\n\n'+NONE
    out=INTRO;boards=collections.OrderedDict()
    for e in sorted(E,key=lambda e:(e['board'],nat(e['revs'][0]),nat(e['refs'][0]))): boards.setdefault(e['board'],[]).append(e)
    for b,es in boards.items():
        out+=f"**{b}**\n\n| Rev | Jumper | What it's for | As shipped | What to do | Needed |\n|---|---|---|---|---|---|\n"
        for e in es:
            out+=f"| {', '.join(e['revs'])} | {', '.join(e['refs'])} | {e['what']} | {e['shipped']} | {e['do']} | {e.get('need') or ''} |\n"
        out+='\n'
    return out
def write(repo,check):
    p=f'{K}6502-{repo}/README.md';t0=open(p,encoding='utf8').read();body=BEGIN+'\n'+section(repo)+END+'\n'
    t=t0.replace('<!-- Jumpers: generated by tools/jumpers/gen.py from jumpers.json. Edit that file, not this section. -->',BEGIN)   # the marker before the tools moved into the repositories
    if BEGIN in t:
        i=t.index(BEGIN);j=t.index(END,i)+len(END)+1;new=t[:i]+body+t[j:]
    else:
        i=t.index('\n## Extra pins');j=t.index('\n## ',i+5);new=t[:j+1]+body+'\n'+t[j+1:]
        new=new.replace('- [Extra pins: `EXP0`–`EXP3` and `HRDB`](#extra-pins-exp0exp3-and-hrdb)\n','- [Extra pins: `EXP0`–`EXP3` and `HRDB`](#extra-pins-exp0exp3-and-hrdb)\n- [Jumpers](#jumpers)\n',1)
    if check: return new==t0
    if new!=t0: open(p,'w',encoding='utf8').write(new)
    return True
def coverage():
    import find
    bad=[];have=collections.defaultdict(dict)
    for e in J:
        for rev in e['revs']:
            for r in e['refs']: have[(e['repo'],e['board'],rev)][r]=e
    for k,js in find.all_jumpers().items():
        for r,(state,val) in js.items():
            e=have.get(k,{}).get(r)
            if not e: bad.append(f'{"|".join(k)} {r} ({val}) is not in jumpers.json');continue
            if state in('open','bridged'):
                s=e['shipped'].lower()
                said='bridged' if (r+' bridged') in e['shipped'] or s.startswith('bridged') else 'open' if (r+' open') in e['shipped'] or s.startswith('open') or s.startswith('both open') else None
                if said and said!=state: bad.append(f'{"|".join(k)} {r}: jumpers.json says {said}, the footprint is {state}')
    for k,rs in have.items():
        pass
    return bad
if __name__=='__main__':
    check='--check' in sys.argv;bad=[]
    for repo in SCOPE:
        if not write(repo,check): bad.append(f'{repo} README Jumpers section is out of date')
    bad+=coverage()
    for b in bad: print(b)
    print('jumpers:',len(J),'entries,',len(bad),'faults');sys.exit(1 if bad else 0)
