"""The base plate, from a machine's assembly file: its outline, its holes, and what uses each hole in each build.

  holes(a)        [Hole]: every plate hole, numbered in reading order (back to front, then left to right)
  positions(a)    [Hole]: the listed board holes with no plate hole under them (S1, S2), numbered after the plate's
  svg(a)          Plate.svg's text: drawn as the computer is used, seen from above, in millimetres
  compare(a)      how the generated plate differs from today's CAD/Bases/Plate.svg

A Hole has x, y, d (None for a listed position), its number or name, and uses: {build name: [(what, kind)]}, where
kind is 'screwed' (a board screws to the plate here), 'resting' (a standoff stands on the plate, no plate hole),
'on_part' (the board screws to a printed part) or 'part' (a printed part screws to the plate).
"""
import math
from assembly import TOL, plate_size, corner_holes, today_plate


class Hole:
    def __init__(self, x, y, d):
        # to 0.01 mm: a board's edge can sit a few micrometres off its holes (the COB Backplane Helper's does), and
        # that shouldn't reach the plate
        self.x, self.y, self.d = round(x, 2), round(y, 2), d
        self.name = ''
        self.uses = {}
        self.added = None

    def use(self, build, what, kind):
        self.uses.setdefault(build, []).append((what, kind))


def _find(hs, x, y):
    return next((h for h in hs if math.hypot(h.x - x, h.y - y) < TOL), None)


_layouts = {}


def holes(a):
    """Every plate hole: one under each screwed board hole, and each printed part's holes."""
    return layout(a)[0]


def positions(a):
    """The listed positions, with what uses each in each build."""
    return layout(a)[1]


def layout(a):
    """(plate holes, listed positions), worked out once for each loaded assembly file."""
    if id(a) not in _layouts:
        _layouts[id(a)] = _layout(a)
    return _layouts[id(a)]


def _layout(a):
    d = a['plate']['hole']
    W, H = plate_size(a)
    out = []
    pos = []
    for name, spec in a.get('positions', {}).items():
        p = Hole(spec['at'][0], spec['at'][1], None)
        p.name = name
        p.spec = spec
        pos.append(p)
    for build in a['builds']:
        for q in build['_placed']:
            for ref, x, y, _ in q.holes():
                p = _find(pos, x, y)
                if p:
                    kind = p.spec['builds'][build['name']]
                    p.use(build['name'], f'{q.name} {ref}', kind)
                    continue
                h = _find(out, x, y)
                if h is None:
                    h = Hole(x, y, d)
                    out.append(h)
                h.use(build['name'], f'{q.name} {ref}', 'screwed')
    for part in a.get('printed_parts', []):
        pts = corner_holes(a, W, H) if part['holes'] == 'corners' else part['holes']
        for x, y in pts:
            h = _find(out, x, y)
            if h is None:
                h = Hole(x, y, part.get('hole', d))
                out.append(h)
            for b in part['builds']:
                h.use(b, part['name'] + (' (optional)' if part.get('optional') else ''), 'part')
    for add in a['plate'].get('added', []):
        h = _find(out, *add['at'])
        if h:
            h.added = add['note']
    out.sort(key=lambda h: (h.y, h.x))
    for i, h in enumerate(out):
        h.name = str(i + 1)
    return out, pos


def _f(v):
    return f'{round(v, 4):g}'


def svg(a):
    """Plate.svg: the outline black, the holes white, in the style of Fusion's Shaper Origin export so LightBurn takes
    it as before; in millimetres, drawn as the computer is used and seen from above."""
    W, H = plate_size(a)
    r = a['plate']['radius']
    out = [f'<?xml version="1.0" encoding="utf-8"?>',
           f'<!-- Generated by Tools/cad/make.py from CAD/Assembly.json and the boards\' PCBs. Edit those, not this file. -->',
           f'<!-- The plate as the computer is used, seen from above: front edge at the bottom. One 3 mm layer; cut {a["plate"]["layers"]}. -->',
           f'<svg xmlns="http://www.w3.org/2000/svg" width="{_f(W)}mm" height="{_f(H)}mm" viewBox="0 0 {_f(W)} {_f(H)}" version="1.1">',
           f'<path d="M{_f(r)},0 L{_f(W - r)},0 A{_f(r)},{_f(r)} 0 0,1 {_f(W)},{_f(r)} L{_f(W)},{_f(H - r)} '
           f'A{_f(r)},{_f(r)} 0 0,1 {_f(W - r)},{_f(H)} L{_f(r)},{_f(H)} A{_f(r)},{_f(r)} 0 0,1 0,{_f(H - r)} '
           f'L0,{_f(r)} A{_f(r)},{_f(r)} 0 0,1 {_f(r)},0z" fill="rgb(0,0,0)" stroke-linecap="round" stroke-linejoin="round" />']
    for h in holes(a):
        rr = h.d / 2
        out.append(f'<path d="M{_f(h.x - rr)},{_f(h.y)} a{_f(rr)},{_f(rr)} 0 1,1 {_f(2 * rr)},0 a{_f(rr)},{_f(rr)} 0 1,1 {_f(-2 * rr)},0z" '
                   f'fill="rgb(255,255,255)" stroke="rgb(0,0,0)" stroke-width="0.01" stroke-linecap="round" stroke-linejoin="round" />')
    out.append('</svg>')
    return '\n'.join(out) + '\n'


def compare(a):
    """[(kind, text)] for every way the generated plate differs from today's Plate.svg, by more than TOL."""
    import fusion
    diffs = []
    W, H = plate_size(a)
    p, turned, today = today_plate(a)
    if abs(p.w - W) > TOL or abs(p.h - H) > TOL:
        diffs.append(('size', f"today's plate is {p.w:g} × {p.h:g}, the generated one {W:g} × {H:g}"))
    radii = fusion.corner_radii(p.outline)
    if radii != [a['plate']['radius']]:
        diffs.append(('corners', f"today's corner radii are {radii}, the generated {a['plate']['radius']}"))
    gen = holes(a)
    for x, y, d in today:
        h = _find(gen, x, y)
        if h is None:
            diffs.append(('removed', f"today's hole at ({x:g}, {y:g}), Ø{d:g}, isn't in the generated plate"))
        elif abs(h.d - d) > 0.01:
            diffs.append(('diameter', f"hole {h.name} at ({x:g}, {y:g}) is Ø{d:g} today and Ø{h.d:g} generated"))
    for h in gen:
        if not any(math.hypot(h.x - x, h.y - y) < TOL for x, y, _ in today):
            diffs.append(('added', f"hole {h.name} at ({h.x:g}, {h.y:g}) is new"))
    return turned, diffs
