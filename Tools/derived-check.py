#!/usr/bin/env python3
"""After any schematic or PCB edit, run this. It lists everything derived from those files, and says what is out of date.
Usage: derived-check.py [--all] [--no-cache]. This repository, or all five with --all. Read-only, except for temp
exports, Tools/work/ and the audit it runs. Exit 1 on any fault.
  Revisions not yet made: production zip against the PCB. Every revision: positions.csv, bom.csv and designators against the PCB,
  images older than a visible change, STEP files that lack a part, 3D model paths that lead nowhere, each repo's own tests, the revision audit, the BOM checker, the library checker, the bus connector schematic check, the label shape check (KICAD.md K25), the off-board headers (K19), REVISIONS.md and the revision labels (K15, K16),
  each machine's CAD/Assembly.json against its boards and plate and the plate files generated from it (CAD.md C3, C4), every card and cart's card edge against the standard (K28), and that Tools/ is the same in every repository
  (sync.py --check)."""
import os,re,glob,json,subprocess,sys,tempfile,zipfile,shutil,collections,hashlib
H=os.path.dirname(os.path.abspath(__file__));sys.path.insert(0,H+'/bom');sys.path.insert(0,H);os.chdir(H+'/bom')
from common import K,SCOPE,ALLFLAG,files,load,present
from apply import footprints,fp_ref,status,gen_bom
sys.path.insert(0,H+'/board-images');from render import visible
KC='/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli';E=[];n=collections.Counter()
sys.path.insert(0,H);from cache import Cache,digest
CACHE=Cache('derived-check',os.path.abspath(__file__))  # slow results, reused while their input files are unchanged
norm=lambda x:{l for l in re.sub(rb'[^\n]*(CreationDate|Created by|GenerationSoftware|TF\.ProjectId|Generated by)[^\n]*\n',b'',x).split(b'\n') if not l.startswith((b'%ADD',b'G04',b'D1',b'D2',b'D3',b'D4',b'D5',b'D6',b'D7',b'D8',b'D9'))}
VIS=re.compile(r'(_Cu|Silkscreen|_Mask|Edge_Cuts)')
R=load('rendered.json')
# the audit first: the checks below read what it writes to Tools/work/audit.json
subprocess.run(['python3',H+'/revision-audit/audit.py',*ALLFLAG],capture_output=True,cwd=H+'/revision-audit');n['audit']+=1
for f in files('Hardware/*/Rev */*.kicad_pcb'):
    p=f.split('/');repo=p[-5];b=p[-3];rv=p[-2];r=rv[4:];short=repo.split('-')[-1];tag=f'{short} {b} {r}';d=K+repo;pd=f'{d}/Production/{b}/{rv}';t=open(f,encoding='utf-8',newline='').read();st=status(short,b,r);n['revisions']+=1
    # bom and positions
    if os.path.exists(pd+'/bom.csv') and open(pd+'/bom.csv',encoding='utf-8',newline='').read()!=gen_bom(t): E.append(f'{tag}: bom.csv out of date')
    F={};
    for s,e in footprints(t):
        x=t[s:e];a=re.search(r'\n\t\t\(attr ([^)]*)\)',x);F[fp_ref(x).upper()]=a.group(1).split() if a else []
    want={k for k,a in F.items() if 'exclude_from_pos_files' not in a and 'dnp' not in a and '**' not in k}
    if os.path.exists(pd+'/positions.csv'):
        have={l.split(',')[0].lstrip('﻿') for l in open(pd+'/positions.csv',encoding='utf-8').read().splitlines()[1:]}
        if have-want: E.append(f'{tag}: positions.csv lists {sorted(have-want)[:5]}, which aren\'t placed')
    # a revision not yet made: its zip must be what the PCB exports today
    if st!='made':
        for s_,e_ in footprints(t):
            x=t[s_:e_];nm=re.match(r'\n\t\(footprint "([^"]*)"',x).group(1)
            if nm.startswith('Package_DIP:') and 'Socket' not in nm: E.append(f'{tag} {fp_ref(x)}: {nm} has no socket; a revision not yet made takes Socket_LongPads')
    if st=='drawn':
        z=glob.glob(pd+'/*.zip')
        if not z: E.append(f'{tag}: no production zip');continue
        def zipcmp(f=f,z=z,tag=tag):
            out=[]
            tmp=tempfile.mkdtemp();subprocess.run([KC,'pcb','export','gerbers','-o',tmp+'/',f,'--subtract-soldermask','--no-x2'],capture_output=True);Z=zipfile.ZipFile(z[0])
            for name in Z.namelist():
                m=re.search(r'-(F_Cu|B_Cu|F_Silkscreen|B_Silkscreen|F_Mask|B_Mask|Edge_Cuts|Top|Bottom)\.',name)
                if not m or name.endswith('.drl'): continue
                alt=[x for x in os.listdir(tmp) if re.search(r'-'+m.group(1).replace('Top','F_Cu').replace('Bottom','B_Cu')+r'\.',x) and not x.endswith('gbrjob')]
                if alt:
                    A=norm(Z.read(name));B=norm(open(f'{tmp}/{alt[0]}','rb').read())
                    if len(A^B)>0: out.append(f'{tag}: {name} in the zip differs from the PCB ({len(A^B)} lines)')
            shutil.rmtree(tmp)
            return out
        zc=CACHE.get('zip '+digest(f,z[0]),zipcmp);n['zips compared']+=1;E.extend(zc)
    stf=f'{d}/CAD/Models/{b}/{rv}/{b}.step'
    if not os.path.exists(stf): E.append(f'{tag}: no STEP')
    else:
        T=set(CACHE.get('step '+digest(stf),lambda:sorted(set(re.findall(r"NEXT_ASSEMBLY_USAGE_OCCURRENCE\('[^']*','([^']*)'",open(stf,errors='replace').read())))));miss=[]
        for s_,e_ in footprints(t):
            x=t[s_:e_];rf=fp_ref(x)
            for q in re.findall(r'\(model "([^"]+)"',x):
                rs=q.replace('${KIPRJMOD}',os.path.dirname(f)).replace('${KICAD10_3DMODEL_DIR}','/Applications/KiCad/KiCad.app/Contents/SharedSupport/3dmodels')
                if not os.path.exists(rs): E.append(f'{tag} {rf}: 3D model not found: {os.path.basename(q)}')
            if '(model "' in x and '**' not in rf and not re.search(r'\(model[^\n]*\n\s*\(hide yes\)',x) and rf not in T: miss.append(rf)
        if miss: E.append(f'{tag}: STEP lacks {sorted(miss)[:6]}')
    if not os.path.exists(f'{d}/Schematics/{b}/{rv}/{b}.pdf'): E.append(f'{tag}: no schematic PDF')
    if not os.path.exists(f'{d}/CAD/Images/{b}/{rv}/Front.png'): E.append(f'{tag}: no images')
    # images and STEP against the PCB's visible content: footprints and their positions, silk text, dnp flags
    vis=visible(t)
    if R and R.get(f'{short}|{b}|{r}')!=vis: E.append(f'{tag}: images were rendered from an older PCB; run Tools/board-images/render.py')
for r in [x for x in ('ACE','COB','KIM') if x in SCOPE]:
    rc=CACHE.get('tests '+digest(f'{K}6502-{r}/Tests/check-schematics.mjs',*sorted(glob.glob(f'{K}6502-{r}/Hardware/*/Rev */*.kicad_sch'))),lambda r=r:subprocess.run(['node','Tests/check-schematics.mjs'],cwd=f'{K}6502-{r}',capture_output=True,text=True).returncode)
    if rc: E.append(f'{r}: Tests/check-schematics.mjs failed')
    n['test suites']+=1
for name,cmd in (('Tools sync check',['python3',H+'/sync.py','--check']),('BOM check',['python3',H+'/bom/check.py']),('CAD check',['python3',H+'/revision-audit/cadcheck.py']),('library check',['python3',H+'/library/check.py']),('schematic check',['python3',H+'/schematic/check.py']),('label shape check',['python3',H+'/schematic/flow.py','--check']),('CAD assembly check',['python3',H+'/cad/assembly.py']),('CAD files check',['python3',H+'/cad/make.py','--check']),('card edge check',['python3',H+'/cardedge/cardedge.py','--check'])):
    x=subprocess.run(cmd+ALLFLAG,capture_output=True,text=True,cwd=os.path.dirname(cmd[1]))
    if x.returncode: E.append(f'{name} failed: '+x.stdout[-200:])
    n[name]+=1
# jumpers: every jumper documented, the READMEs' tables current (Tools/jumpers/gen.py --check)
_data=lambda name:[f'{K}6502-{r}/Tools/data/{name}' for r in present()]
_jin=files('Hardware/*/Rev */*.kicad_sch')+files('Hardware/*/Rev */*.kicad_pcb')+files('README.md')+_data('jumpers.json')+[H+'/jumpers/gen.py',H+'/jumpers/find.py',H+'/common.py']
_jr=CACHE.get('jumpers '+' '.join(SCOPE)+' '+digest(*_jin),lambda:(lambda x:[x.returncode,x.stdout[-400:]])(subprocess.run(['python3',H+'/jumpers/gen.py','--check',*ALLFLAG],capture_output=True,text=True)))
if _jr[0]: E.append('jumpers check failed: '+_jr[1])
n['jumpers check']+=1
# off-board headers: every header on a newest revision classified, on the right connector, the READMEs' tables current (KICAD.md K19)
_oin=files('Hardware/*/Rev */*.kicad_pcb')+files('README.md')+files('Tools/work/audit.json')+_data('offboard.json')+_data('jumpers.json')+[H+'/offboard/offboard.json',H+'/offboard/gen.py',H+'/common.py']
_or=CACHE.get('offboard '+' '.join(SCOPE)+' '+digest(*_oin),lambda:(lambda x:[x.returncode,x.stdout[-400:]])(subprocess.run(['python3',H+'/offboard/gen.py','--check',*ALLFLAG],capture_output=True,text=True)))
if _or[0]: E.append('off-board headers check failed: '+_or[1])
n['off-board headers check']+=1
# REVISIONS.md, the README's "Which revision to make" and the labels (KICAD.md K15, K16): current with audit.json and orders.json
_rr=subprocess.run(['python3',H+'/revision-audit/register.py','--check',*ALLFLAG],capture_output=True,text=True,cwd=H+'/revision-audit')
if _rr.returncode: E.append('register check failed: '+_rr.stdout[-400:])
n['register check']+=1
for a in load('audit.json'):
    if a['repo'] in SCOPE and a['issues']: E.append(f"audit: {a['repo']} {a['board']} {a['rev']}: {a['issues']}")
CACHE.save();n['cache reused']=CACHE.hits;n['computed']=CACHE.misses
print(dict(n));print('faults',len(E));[print(' ',x) for x in E[:40]];sys.exit(1 if E else 0)
