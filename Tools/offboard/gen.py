#!/usr/bin/env python3
"""Writes the "Off-board headers" section of the README from offboard.json, Tools/data/offboard.json and the PCB file
of each board's newest revision. With --all, in all five repositories.

  gen.py            write the README
  gen.py --check    exit 1 if a README is out of date, a header on a newest revision isn't classified, or an off-board
                    header is on the wrong connector for its kind of build
  gen.py --list     print every header found, and how it was classified

Off-board headers are for a machine built into a case: the case's jack, switches, LEDs and keyboard wire to the board
through them, and the matching parts on the board are left off. offboard.json says what each kind is for; the
references in the table, and the parts it says to leave off, are read from the PCB."""
import os,sys,json,re,collections
H=os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0,H+'/../bom');from apply import footprints,fp_ref
from common import K,SCOPE,load
J=json.load(open(H+'/offboard.json'));J.update({k:v for k,v in load('offboard.json').items() if not k.startswith('_')})   # the family's kinds, and each repository's exceptions
AUD=load('audit.json')
JUMP={(e['repo'],e['board'],rev,r) for e in load('jumpers.json') for rev in e['revs'] for r in e['refs']}
BEGIN='<!-- Off-board headers: generated by Tools/offboard/gen.py from Tools/offboard/offboard.json, Tools/data/offboard.json and the PCB files. Edit those, not this section. -->'
END='<!-- End of off-board headers -->'
INTRO="""## Off-board headers

Some boards have small headers, such as `RESET SW`, `CLOCK ENBL SW`, `POWER LED` and `VCC`, that a standard build leaves empty. They are for a machine built into a full enclosure, which AC6502 doesn't offer today. In such a build, the parts a person handles are mounted on the case and wired to the board through these headers: the power jack, the switches, the LEDs and the keyboard. The matching parts on the board are then left off. For example, an ACE Board can sit inside a case with its power jack, power switch and key switches left off, and a Keyboard Helper as its keyboard.

To build a board for a case:

1. Fit the header, and wire the part on the case to it. The table says what goes on each pin.
2. Leave off the parts on the board that the table names. A button on the case can work beside the board's own button, but some parts, such as an LED that shares the board's resistor, can't share.
3. Set any jumper the table mentions. The [Jumpers](#jumpers) section has the rest.

The connector follows the kind of build. A single-board machine, the ACE Board or the KIM Board, uses plain 2.54 mm pin headers, which are simpler and cheaper. A board in a multi-board machine, every COB board and the separate boards of the VCS, the DEV and the KIM, uses JST XH, the family's standard for these headers.

"""
TABLE="The table lists every off-board header on each board's newest revision, read from the board's PCB file.\n\n| Board | Rev | Header | Label | Connector | What it's for | Leave off |\n|---|---|---|---|---|---|---|\n"
NONE="None of this repository's boards has an off-board header at its newest revision.\n\n"
def nat(s): return [int(x) if x.isdigit() else x for x in re.split(r'(\d+)',s)]
def ranges(refs):
    """SW1, SW2, SW3, SW5 -> SW1–SW3 and SW5"""
    by=collections.defaultdict(list)
    for r in refs:
        m=re.match(r'([A-Z]+)(\d+)$',r);by[m.group(1)].append(int(m.group(2)))
    out=[]
    for p,ns in sorted(by.items()):
        ns=sorted(set(ns));i=0
        while i<len(ns):
            j=i
            while j+1<len(ns) and ns[j+1]==ns[j]+1: j+=1
            out.append(f'{p}{ns[i]}' if j==i else f'{p}{ns[i]}, {p}{ns[j]}' if j==i+1 else f'{p}{ns[i]}–{p}{ns[j]}');i=j+1
    return out[0] if len(out)==1 else ', '.join(out[:-1])+' and '+out[-1]
def parts(t):
    """{ref: (value, footprint, {pad: net})}"""
    P={}
    for s,e in footprints(t):
        b=t[s:e];r=fp_ref(b)
        fp=re.match(r'\n\t\(footprint "([^"]*)"',b).group(1);v=re.search(r'\(property "Value" "([^"]*)"',b).group(1)
        pads={m.group(1):m.group(2) for m in re.finditer(r'\(pad "([^"]*)"[^\n]*(?:\n[^\n]*?){0,30}?\(net (?:\d+ )?"([^"]*)"',b)}
        P[r]=(v,fp,pads)
    return P
def connector(fp):
    m=re.search(r'JST_XH_[\w-]+?_1x(\d+)',fp)
    if m: return f'JST XH, {int(m.group(1))} pins'
    m=re.search(r'Pin(Header|Socket)_(\d+)x(\d+)_P([\d.]+)mm',fp)
    if m: return f'Pin {m.group(1).lower()}, {int(m.group(2))}×{int(m.group(3))}, {float(m.group(4)):.2f} mm'
    return fp.split(':')[-1]
def headers(repo,board,rev):
    """Every pin header, pin socket and JST XH header on one revision: [(ref, value, footprint, class, reason)]."""
    t=open(f'{K}6502-{repo}/Hardware/{board}/Rev {rev}/{board}.kicad_pcb',encoding='utf8').read();P=parts(t);out=[]
    for r,(v,fp,pads) in sorted(P.items(),key=lambda x:nat(x[0])):
        if not re.match(r'J\d+$',r) or not re.search(r'PinHeader|PinSocket|JST_XH',fp): continue
        k=f'{repo}|{board}|{r}'
        if k in J['not_offboard_refs']: out.append((r,v,fp,'other',J['not_offboard_refs'][k]))
        elif v in J['kinds']: out.append((r,v,fp,'offboard',''))
        elif (repo,board,rev,r) in JUMP: out.append((r,v,fp,'jumper',''))
        elif v in J['not_offboard']: out.append((r,v,fp,'other',J['not_offboard'][v]))
        else: out.append((r,v,fp,'unknown',''))
    return out,P
def fill(text,kind,ref,P):
    pads=P[ref][2];nets={n for n in pads.values() if n not in('GND','VCC')};found={}
    for name,(scope,pre,rx) in kind['find'].items():
        hits=[r for r,(v,fp,pp) in P.items() if r!=ref and re.match(pre+r'\d+$',r) and (not rx or re.search(rx,v) or re.search(rx,fp)) and (scope=='board' or nets & set(pp.values()))]
        if not hits: raise LookupError(f'{ref}: no part for {{{name}}} ({scope}, {pre}, {rx!r})')
        found[name]=ranges(hits)
    return re.sub(r'\{(\w+)\}',lambda m:found[m.group(1)],text)
def newest(repo):
    return sorted([(a['board'],a['rev']) for a in AUD if a['repo']==repo and a['newest']])
def section(repo,faults):
    rows=[]
    for board,rev in newest(repo):
        hs,P=headers(repo,board,rev);single=f'{repo}|{board}' in J['single_board']
        for r,v,fp,cls,why in hs:
            tag=f'{repo} {board} {rev} {r} ({v})'
            if cls=='unknown': faults.append(f'{tag}: not classified; add it to Tools/offboard/offboard.json, Tools/data/offboard.json or Tools/data/jumpers.json');continue
            if cls!='offboard': continue
            want=J['connector']['single' if single else 'multi']
            if want not in fp and f'{repo}|{board}|{r}' not in J['connector_accepted']:
                faults.append(f"{tag}: a {'single' if single else 'multi'}-board build takes {want}, not {fp.split(':')[-1]}")
            kind=J['kinds'][v]
            try: rows.append((board,rev,r,v,connector(fp),fill(kind['what'],kind,r,P),fill(kind['leave'],kind,r,P)))
            except LookupError as e: faults.append(f'{tag}: {e}')
    if not rows: return INTRO+NONE
    return INTRO+TABLE+''.join(f'| {b} | {rv} | {r} | `{v}` | {c} | {w} | {l} |\n' for b,rv,r,v,c,w,l in rows)+'\n'
def write(repo,check,faults):
    p=f'{K}6502-{repo}/README.md';t0=open(p,encoding='utf8').read();body=BEGIN+'\n'+section(repo,faults)+END+'\n'
    t=t0.replace('<!-- Off-board headers: generated by tools/offboard/gen.py from offboard.json and the PCB files. Edit those, not this section. -->',BEGIN)   # the marker before the tools moved into the repositories
    if BEGIN in t:
        i=t.index(BEGIN);j=t.index(END,i)+len(END)+1;new=t[:i]+body+t[j:]
    else:
        i=t.index('<!-- End of jumpers -->\n')+len('<!-- End of jumpers -->\n');new=t[:i]+'\n'+body+t[i:]
        new=new.replace('- [Jumpers](#jumpers)\n','- [Jumpers](#jumpers)\n- [Off-board headers](#off-board-headers)\n',1)
    if check: return new==t0
    if new!=t0: open(p,'w',encoding='utf8').write(new)
    return True
if __name__=='__main__':
    if '--list' in sys.argv:
        for repo in SCOPE:
            for board,rev in newest(repo):
                for r,v,fp,cls,why in headers(repo,board,rev)[0]: print(f'{repo:4}{board:26}{rev:5}{r:5}{cls:9}{v:22}{connector(fp):28}{why}')
        sys.exit(0)
    check='--check' in sys.argv;faults=[]
    for repo in SCOPE:
        if not write(repo,check,faults): faults.append(f'{repo} README "Off-board headers" is out of date: run Tools/offboard/gen.py')
    for k,why in J['connector_accepted'].items():
        if k.split('|')[0] in SCOPE: print('accepted:',k,'-',why)
    for f in faults: print(f)
    print('off-board headers:',len(faults),'faults');sys.exit(1 if faults else 0)
