#!/usr/bin/env python3
"""Write REVISIONS.md, and the README's "Which revision to make" section, in each AC6502 KiCad repo from audit.json,
orders.json and the saved Tindie listings. The labels (KICAD.md K15, K16) come from labels.py.
Usage: audit.py && register.py [--all]        register.py --check exits 1 if any of those files is out of date."""
import json,os,re,glob,hashlib,collections,sys
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)));import labels
CHECK='--check' in sys.argv;STALE=[]
H=os.path.dirname(os.path.abspath(__file__));from common import K as BASE,SCOPE,load
R=load('audit.json');O=load('orders.json')
TIN=load('tindie.json')   # stock on each board's Tindie listing, as saved; see its _about
def tindie(repo,b): return TIN.get(f'{repo}|{b}')
def corner(x):
    c=x.get('corner') or []
    if not c or abs((x.get('size') or [0,0])[1]-57.62)<.1 or x['board'] in('Flash Cart','ROM Cart'): return '—'
    v=sorted({a for p in c for a in p})
    if all(abs(a-6)<=.1 for a in v): return '6 mm'
    if all(abs(a-5)<=.1 for a in v): return '5 mm'
    return f'{min(v):g}–{max(v):g} mm'
INTRO="""# Revisions

Every revision of every board in this repository, and what is known about each. The dates of the checks are at the end.

**Status** says what has happened to a revision:

- **Made, matches order:** JLCPCB's own copy of the order is byte-identical to the production zip here, and the PCB file regenerates the same copper, mask, outline and holes. This compares files with the order. It says nothing about whether the board works: that's the **Label**.
- **Made, not compared:** the board exists, but its files haven't been compared with an order.
- **Ordered:** placed, and not yet arrived.
- **Drawn:** the files are complete, and the board hasn't been ordered.
- **Never made**, or **To confirm** where nothing on record says either way.

**Label** says whether a builder can rely on a revision. Make the newest revision of a board, and check its label first:

- **Tested:** {T}
- **Proven design:** {P}
- **Untested:** {U}

**Holes** is how far the corner mounting holes sit from the board's edges. The standard is 6 mm, and 5 mm on the ACE Board, the CF Adapter and the Keyboard Helper. A dash means a card or cart, which has no corner holes.

""".format(T=labels.DEFINE['Tested'],P=labels.DEFINE['Proven design'],U=labels.DEFINE['Untested'])
RB='<!-- Which revision to make: generated by Tools/revision-audit/register.py from Tools/data/orders.json. Edit that file, not this section. -->'
RE='<!-- End of which revision to make -->'
RINTRO="""## Which revision to make

**Make the newest revision of a board, and check its label first.** The table below gives each board's newest revision. A newer revision fixes what was found on the older ones. Every revision, old and new, is in [REVISIONS.md](REVISIONS.md), with what changed in each.

Each revision carries one of three labels:

- **Tested:** {T}
- **Proven design:** {P}
- **Untested:** {U}

[BOM.md](BOM.md) has the parts for every revision, and its known issues.

| Board | Newest revision | Label | Why |
|---|---|---|---|
""".format(T=labels.DEFINE['Tested'],P=labels.DEFINE['Proven design'],U=labels.DEFINE['Untested'])
def readme_section(repo):
    out=RINTRO;B=collections.OrderedDict()
    for x in sorted([r for r in R if r['repo']==repo],key=lambda r:(r['board'],r['rev'])): B.setdefault(x['board'],[]).append(x['rev'])
    for b,revs in B.items():
        new=[x['rev'] for x in R if x['repo']==repo and x['board']==b and x['newest']][0]
        base=re.sub(r'[a-z]$','',new);sib=[r for r in revs if re.sub(r'[a-z]$','',r)==base] if base!=new else [new]
        L=[labels.label(repo,b,r) for r in sib]
        if len(sib)==1: why=L[0][1]
        else: why='; '.join(f"Rev {r} {labels.lower(w.replace(labels.TESTED+'. ',''))}" for r,(n,w) in zip(sib,L))
        n=L[0][0] if len({l[0] for l in L})==1 else ' / '.join(l[0] for l in L)
        why=why.rstrip('.')+'.'
        out+=f"| {b} | {' or '.join(sib)} | **{n}** | {why} |\n"
    return out
def write_readme(repo):
    p=f'{BASE}6502-{repo}/README.md';t0=open(p,encoding='utf8').read();body=RB+'\n'+readme_section(repo)+RE+'\n'
    t=t0.replace('<!-- Which revision to make: generated by tools/revision-audit/register.py from orders.json. Edit that file, not this section. -->',RB)   # the marker before the tools moved into the repositories
    if RB in t:
        i=t.index(RB);j=t.index(RE,i)+len(RE)+1;new=t[:i]+body+t[j:]
    else:
        i=t.index('\n## Hardware');j=t.index('\n## ',i+5);nxt=t[j+4:t.index('\n',j+4)]
        new=t[:j+1]+body+'\n'+t[j+1:]
        a=re.sub(r'[^a-z0-9 -]','',nxt.lower()).replace(' ','-');toc=f'- [{nxt}](#{a})\n'
        if toc not in new: raise SystemExit(f'{repo}: no table-of-contents line {toc!r}')
        new=new.replace(toc,'- [Which revision to make](#which-revision-to-make)\n'+toc,1)
    if new!=t0:
        if CHECK: STALE.append(f'{repo} README "Which revision to make"')
        else: open(p,'w',encoding='utf8').write(new)
for repo in SCOPE:
    os.chdir(BASE+'6502-'+repo);rows=[];cnt=collections.Counter()
    out=INTRO+'| Board | Rev | Status | Label | Order | Ordered | Made from | Tindie stock | Size (mm) | Holes | Top panel | Enclosure | Notes |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n'
    for x in sorted([r for r in R if r['repo']==repo],key=lambda r:(r['board'],r['rev'])):
        k=f"{repo}|{x['board']}|{x['rev']}";b=x['board'];rev='Rev '+x['rev'];oi=gd=src='';notes=[]
        if k in O['made']: st='Made, matches order';oi,gd,src=O['made'][k];src='`'+src+'`'
        elif k in O['drawn']: st='Drawn'
        elif k in O['never']: st='Never made'
        elif k in O['ordered']: st='Ordered';notes.append(O['ordered'][k])
        elif k in O['made_unchecked']: st='Made, not compared';notes.append(O['made_unchecked'][k])
        else: st='To confirm'
        cnt[st]+=1;newest=x['newest'];ti=tindie(repo,b) if st.startswith(('Made','To')) and x['rev'] in('1.0','1.0a','1.0b') or k=='COB|Backplane Pro|1.1' else None
        # Only tracked file types count: LightBurn and slicer files (.lbrn2, .3mf, .bgcode) are the owner's, untracked.
        top='yes' if glob.glob(f'CAD/Tops/{b}/{rev}/*.svg') else '—'
        enc='yes' if [f for f in glob.glob(f'CAD/Enclosures/{b}/{rev}/*') if not f.endswith(('.lbrn2','.3mf','.bgcode'))] else '—'
        if x.get('known'): notes.append('symbol has pins the footprint lacks: '+x['known'])
        if x.get('note'): notes.append(x['note'])
        if k in O.get('notes',{}): notes.append(O['notes'][k])
        notes+=[i for i in x['issues']]
        if newest and st=='Made, matches order' and any(r['board']==b and r['rev']!=x['rev'] and r['repo']==repo for r in R): pass
        sz='×'.join(f'{v:g}' for v in x['size']) if x.get('size') else 'in footprint'
        out+=f"| {b} | {x['rev']} | {st} | {labels.cell(repo,b,x['rev'])} | {oi} | {gd} | {src} | {ti if ti is not None else '—'} | {sz} | {corner(x)} | {top} | {enc} | {'; '.join(notes)} |\n"
    out+=f"\nJLCPCB's orders were checked on 2026-11-04: each production zip marked *Made, matches order* was compared byte for byte with JLCPCB's copy, and its PCB regenerated to the same copper, mask, outline and holes. Each time this table is written, every PCB is checked again against its production zip, for copper and drill holes. Tindie stock is from the listings as saved on 2026-10-23.\n"
    HS='<!-- History: hand-written. Tools/revision-audit/register.py keeps everything from here to the end. -->'
    HS_OLD=HS.replace('Tools/','tools/')
    old=open('REVISIONS.md',encoding='utf8').read() if os.path.exists('REVISIONS.md') else ''
    keep=old.replace(HS_OLD,HS)
    if HS in keep: out=out.rstrip('\n')+'\n\n'+keep[keep.index(HS):]
    if old!=out:
        if CHECK: STALE.append(f'{repo} REVISIONS.md')
        else: open('REVISIONS.md','w',encoding='utf8').write(out)
    write_readme(repo)
    if not CHECK: print(repo,dict(cnt))
if CHECK:
    for x in STALE: print(x,'is out of date: run Tools/revision-audit/register.py')
    sys.exit(1 if STALE else 0)
